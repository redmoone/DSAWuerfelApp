   await master.locator('.nav-links a[href="kampf"]').click();
   await master.locator('.nav-links a[href=""]').click();
   await master.getByRole('button',{name:'Zur W\u00fcrfelseite',exact:true}).click();
   await master.locator('canvas').waitFor();

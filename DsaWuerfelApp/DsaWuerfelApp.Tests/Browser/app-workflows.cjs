  await player.getByRole('button',{name:'W20 auf Aberglaube',exact:true}).click();
  await player.locator('[data-roll-kind="bad-trait"]').waitFor();
  assert.ok((await player.locator('[data-roll-kind="bad-trait"] [data-testid="current-roll-status"]').innerText()).trim());

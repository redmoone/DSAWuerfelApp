  await player.locator('.probe-info-summary').waitFor();
  assert.ok((await player.locator('.probe-info-summary-text').innerText()).trim());
  await player.locator('.probe-info-button').click();
  await player.locator('.probe-info-details').waitFor({state:'visible'});
  await player.getByRole('button',{name:'Probeninformationen schliessen',exact:true}).click();
  await player.locator('.probe-info-details').waitFor({state:'hidden'});
  await player.locator('.spell-selection-group').first().locator('summary').first().click();
  const enabledSpellOption=player.locator('.spell-selection-button:not(:disabled):visible').first();

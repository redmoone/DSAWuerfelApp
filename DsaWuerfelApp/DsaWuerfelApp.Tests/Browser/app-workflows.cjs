  await player.locator('.results-bar button.dsa-btn').click();
  await player.locator('[data-roll-kind="spell"]').waitFor();
  assert.ok((await player.locator('[data-roll-kind="spell"] [data-testid="current-roll-status"]').innerText()).trim());
  await waitFor(async()=> (await details()).history.length===2,'spell roll missing');
  const spellHistoryEntry=player.locator('[data-testid="history-panel"] .history-entry').filter({hasText:'Abvenenum'}).first();
  await spellHistoryEntry.waitFor();
  assert.equal(await spellHistoryEntry.locator('.history-check').count(),3);
  const spellCheckStates=await spellHistoryEntry.locator('.history-check-state').allTextContents();
  assert.ok(spellCheckStates.every(state=>['im Ziel','ausgeglichen','fehlgeschlagen'].includes(state.trim())));
  const spellCheckLabels=await spellHistoryEntry.locator('.history-check').evaluateAll(elements=>elements.map(element=>element.getAttribute('aria-label')));
  assert.ok(spellCheckLabels.every(label=>label && label.includes('von')));
